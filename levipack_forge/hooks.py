"""Native hook registry: one entry per Java feature that needs a Bedrock hook.

Only documented, compile-safe C++ is generated (no guessing of SDK macros). The registry
* logs every un-installed hook at start-up so gaps are visible in the launcher log,
* lists Bedrock symbol candidates (from --symbols) next to each feature,
* has a single marked place (HOOK-POINT) per feature where the hook is installed with
  `<pl/memory/Hook.hpp>` once the symbol is verified against the exact Bedrock version.
"""
from __future__ import annotations
from .transpile import cstr

H = '''#pragma once

#include <pl/Mod.hpp>

namespace @NS@::hooks {

// Installs every native hook that has been wired up; logs the ones that still need work.
void installAll(ll::mod::NativeMod &self);
void uninstallAll(ll::mod::NativeMod &self);

// Address of a vtable slot's target in libminecraftpe.so, or nullptr when the loaded build
// is not the one the table was calibrated on (never hook on a mismatch).
void *resolveItemSlot(const char *name);

} // namespace @NS@::hooks
'''

CPP = '''// Generated by levipack-forge. One row per Java feature that has no automatic Bedrock equivalent.
#include "mod/Hooks.h"

#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <string_view>
#include <vector>

namespace @NS@::hooks {
namespace {

struct HookInfo {
    std::string_view feature;     // what the Java mod did
    std::string_view category;    // kind of work (commands, rendering, ...)
    std::string_view how;         // suggested way to solve it
    std::vector<std::string_view> symbols; // Bedrock symbol candidates (heuristic, verify before hooking)
    bool installed;
};

// Verified Item field offsets (raw; use only after resolveItemSlot() succeeded).
@LAYOUT@

// Verified Item vtable slots (build sha256 4de40e1d...). Itanium ABI: slot holds an absolute
// address after relocation, so target = *(base + vptr_rva + 8*slot); it must equal base + expectedRva.
struct SlotInfo { const char *name; uintptr_t vptrRva; int slot; uintptr_t expectedRva; void *orig; };

std::vector<SlotInfo> &slots() {
    static std::vector<SlotInfo> t = {
@SLOTS@
    };
    return t;
}

// Lowest mapping of libminecraftpe.so in /proc/self/maps (image base is 0, so RVA == offset from this).
uintptr_t moduleBase() {
    static uintptr_t base = 0;
    if (base) return base;
    FILE *f = std::fopen("/proc/self/maps", "r");
    if (!f) return 0;
    char line[1024];
    while (std::fgets(line, sizeof line, f)) {
        if (std::strstr(line, "libminecraftpe.so")) {
            base = std::strtoull(line, nullptr, 16);
            break;
        }
    }
    std::fclose(f);
    return base;
}

std::vector<HookInfo> &table() {
    static std::vector<HookInfo> t = {
@ROWS@
    };
    return t;
}

} // namespace

void *resolveItemSlot(const char *name) {
    uintptr_t base = moduleBase();
    if (!base) return nullptr;
    for (auto &s : slots()) {
        if (std::strcmp(s.name + 6, name) != 0) continue;   // skip "Item::"
        uintptr_t target = *reinterpret_cast<uintptr_t *>(base + s.vptrRva + 8 * static_cast<uintptr_t>(s.slot));
        return target == base + s.expectedRva ? reinterpret_cast<void *>(target) : nullptr;
    }
    return nullptr;
}

void installAll(ll::mod::NativeMod &self) {
    size_t okSlots = 0;
    for (auto &s : slots())
        if (resolveItemSlot(s.name + 6)) ++okSlots;
    if (okSlots == slots().size())
        self.getLogger().info("{} verified Item vtable slots resolved (build matches)", okSlots);
    else
        self.getLogger().warn("only {}/{} Item slots match; native hooks stay disabled for this game build", okSlots, slots().size());
    size_t pending = 0;
    for (auto &h : table()) {
        // HOOK-POINT: resolve the symbol (pl/memory/Signature.hpp), install the hook (pl/memory/Hook.hpp),
        // then set h.installed = true. Read the matching `cmd_*` config fields inside the hook body.
        if (!h.installed) {
            ++pending;
            self.getLogger().debug("[hook] not installed: {} ({})", std::string(h.feature), std::string(h.category));
        }
    }
    if (pending)
        self.getLogger().warn("{} Java feature(s) are not ported to native hooks yet (see CONVERSION_REPORT.md)", pending);
}

void uninstallAll(ll::mod::NativeMod &self) {
    for (auto &h : table())
        h.installed = false;
    self.getLogger().debug("hooks released");
}

} // namespace @NS@::hooks
'''


def render(ns, issues, commands, sym=None):
    from . import vtable
    slot_rows = vtable.cpp_table(vtable.load())
    rows, seen = [], set()
    for it in issues:
        key = it["what"]
        if key in seen:
            continue
        seen.add(key)
        syms = sym.hints_for(it["what"]) if sym is not None else []
        vh = vtable.item_hook_for(it["what"])
        if vh:
            syms = [f"vtable Item slot {vh[1]} (RVA {vh[2]:#x}, verified)"] + list(syms)
        sl = ", ".join(cstr(s) for s in syms)
        rows.append(f'        {{{cstr(it["what"])}, {cstr(it["category"])}, {cstr(it["fix"])}, {{{sl}}}, false}},')
    for c in commands:
        what = f"command /{c['path']} -> config cmd_* field (value is stored; a hook must apply it)"
        rows.append(f'        {{{cstr(what)}, "Commands", "Apply the stored config value inside the hook that implements this feature.", {{}}, false}},')
    body = "\n".join(rows) if rows else "        // (nothing to hook)"
    return H.replace("@NS@", ns), CPP.replace("@NS@", ns).replace("@SLOTS@", slot_rows).replace("@LAYOUT@", vtable.cpp_layout()).replace("@ROWS@", body)
